/**
 * vision-proxy agent hook script.
 *
 * Auto-generated by vp integration install. Do not edit by hand; re-run
 * the installer to regenerate after a vision-proxy upgrade.
 *
 * Prerequisite: tsx must be installed for the host npx tsx command to
 * run this file (e.g. npm install -g tsx).
 *
 * Handles UserPromptSubmit and PreToolUse events: UserPromptSubmit emits
 * a static reminder for prompt image paths and pasted or attached
 * image refs resolved via the image cache (never shells out, so prompt
 * submission is never blocked). The reminder names the host's native image
 * tool (Read for Claude Code, view_image for Codex, stamped at generate()
 * time), while PreToolUse analyzes Read-tool or
 * view_image image paths by shelling out to vp analyze, then emits
 * hookSpecificOutput.additionalContext with a deny decision for the agent.
 *
 * The PreToolUse analysis is grounded in the recent conversation: the host
 * hands the hook a transcript_path on stdin (CC JSONL, Codex rollout) whose
 * last user/assistant turns are read from disk and formatted into
 * vp analyze --context. The read is bounded and fails open, so a missing or
 * unreadable transcript simply means the analyze call runs without context.
 *
 * Fail-open: on any error it exits 0 with no stdout, so the agent proceeds
 * unchanged. Image-derived text is attacker-controlled, so the analyzer
 * fence stays on.
 */

