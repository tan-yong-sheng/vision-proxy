/**
 * Embedded Pi extension source.
 *
 * `vp integration install pi` writes this exact TypeScript into Pi's global
 * extensions directory (`~/.pi/agent/extensions/vision-proxy_read.ts`). Pi auto-loads
 * it via its `jiti` loader, so it must run as plain TypeScript with no build step.
 *
 * The extension hooks into Pi's lifecycle events at parity with the Claude Code /
 * Codex hook script integration:
 *   - `input`: a no-op that returns immediately so the user's prompt is accepted
 *     and submitted the instant they press Enter. It never awaits `vp analyze`,
 *     so prompt submission is never blocked on the vision call.
 *   - `context`: fires right before Pi sends the turn's messages to the model.
 *     For each user message it finds image paths referenced in the text and
 *     appends a static reminder to inspect each one with the read tool. It
 *     never shells out to `vp analyze`, so it adds no latency: the actual
 *     analysis happens lazily in the `tool_result` handler when the model
 *     reads the image. Inline image attachments are left untouched so the
 *     model sees them natively.
 *   - `tool_result`: the single analysis point. Intercepts `read` tool results
 *     on image files and replaces the tool result content with the fenced
 *     UNTRUSTED description from `vp analyze` so no image bytes reach the model.
 *     The last user/assistant messages of the session branch are formatted
 *     into `vp analyze --context` (via `ctx.sessionManager.getBranch()`) so the
 *     description is grounded in the recent conversation.
 *
 * Pi fires the `input` event for every `session.prompt()` submission, including
 * ones that arrive while the agent is streaming and are queued via the
 * `streamingBehavior` option. Queued streaming prompts flow through the same
 * `context` reminder path, so no prompt submit is ever blocked.
 *
 * No tool is registered, keeping system tokens low.
 *
 * Fail-open: if `vp` is missing, exits non-zero, or any other error occurs, the
 * extension returns undefined and Pi proceeds unchanged. Image-derived text is
 * attacker-controlled, so the analyzer fence stays on.
 *
 * Composition: the shared analysis policy (path classification, env parsing,
 * reminder rendering, vp resolution) is inlined from the canonical runtime
 * (`src/integrations/runtime.ts`) at generate() time; the adapter below owns only
 * Pi lifecycle translation, mode gating, the async executor with AbortSignal
 * handling, and the tool_result output shape. The emitted file stays
 * standalone (no package import).
 *
 * NOTE: this module exports the extension source as a raw string. It uses
 * String.raw so regexes inside the generated source are written exactly once.
 * The generated source must therefore never contain a backtick or a dollar
 * sign followed by an opening brace.
 */
